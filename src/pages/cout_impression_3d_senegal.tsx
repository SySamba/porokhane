    <p>Le premier facteur est <strong>la matière</strong>. Le PLA peut convenir à une maquette ou à un prototype visuel ; le PETG ou d'autres matériaux peuvent être préférables selon les contraintes mécaniques, thermiques ou environnementales. Le prix de la matière consommée dépend du matériau, de la masse réellement utilisée et des pertes éventuelles.</p>
